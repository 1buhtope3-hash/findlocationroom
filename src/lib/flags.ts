export function isoFor(country: string): string | null {
  if (country in ISO) return ISO[country];
  if (country.startsWith("США")) return "US";
  return null;
}

export function flagEmoji(country: string): string | null {
  const code = isoFor(country);
  if (!code) return null;
  return String.fromCodePoint(...[...code].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65));
}
